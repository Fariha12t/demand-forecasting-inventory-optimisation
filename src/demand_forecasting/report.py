"""Generate docs/model_comparison_report.md from the latest pipeline outputs."""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from .config import PROJECT_ROOT, resolve


def _md(df: pd.DataFrame, nd: int = 3) -> str:
    return df.round(nd).to_markdown(index=False) if hasattr(df, "to_markdown") and _has_tabulate() else \
        "```\n" + df.round(nd).to_string(index=False) + "\n```"


def _has_tabulate() -> bool:
    try:
        import tabulate  # noqa: F401
        return True
    except Exception:
        return False


def write_report(cfg: dict) -> Path:
    out = resolve(cfg, "outputs_dir")
    rd = lambda n: pd.read_csv(out / n) if (out / n).exists() else None
    mv, mt, sim, el = rd("metrics_val.csv"), rd("metrics_test.csv"), rd("policy_simulation.csv"), rd("price_elasticity.csv")
    imp = rd("feature_importance.csv")
    sig = out / "r" / "model_significance.csv"
    an = json.loads((out / "anomaly_metrics.json").read_text()) if (out / "anomaly_metrics.json").exists() else {}
    mon = json.loads((out / "monitoring_summary.json").read_text()) if (out / "monitoring_summary.json").exists() else {}
    src = cfg["data"]["source"]
    L = ["# Model comparison & evaluation report", "",
         f"_Generated by `python -m demand_forecasting.pipeline report`. Data source: **{src}**"
         + (" (synthetic - numbers illustrate the method, they are not M5 results)" if src == "synthetic" else "") + "._", "",
         "## Protocol", "",
         "- **Time-based split**: train -> validation (28 days, model selection, early stopping inside train) -> test (last 28 days, untouched). No random splitting.",
         "- **Multi-step forecasting**: every model forecasts the full 28-day window from a single origin; tree models forecast recursively, feeding their own predictions back as lags. Planned prices/promotions/events are known inputs.",
         "- **Test fold models are refit on train+validation** with the tree count chosen on validation.",
         "- **Metrics**: MAE, RMSE, WAPE (sum|e| / sum y), MASE (scaled by in-sample seasonal-naive MAE, <1 beats it), WAPE_weekly (error after aggregating to weekly buckets - the ordering cadence), Bias.", ""]
    if mv is not None:
        L += ["## Validation results", "", _md(mv), ""]
    if mt is not None:
        L += ["## Test results", "", _md(mt), ""]
    if sig.exists():
        L += ["## Statistical significance (R)", "",
              "Friedman test + Holm-adjusted pairwise Wilcoxon tests on per-series test MAE (`r/03_model_significance.R`).", "",
              _md(pd.read_csv(sig), 4), ""]
    if sim is not None:
        L += ["## Inventory back-test", "",
              "Same forecast-driven (s, S) policy on actual test-window demand; only the forecast differs. Costs = holding cost + lost gross margin "
              "on unmet demand. Cost depends on forecast *bias and calibration* as well as accuracy, and differences over one 28-day window can be noise.", "", _md(sim, 2), ""]
    if el is not None:
        L += ["## Price elasticity", "", _md(el), ""]
    if imp is not None:
        L += ["## Feature importance (serving model)", "", _md(imp.head(10), 4), ""]
    if an:
        L += ["## Anomaly detection", "", f"Against injected anomalies: precision {an['precision']:.0%}, recall {an['recall']:.0%} "
              f"(spikes {an['recall_spikes']:.0%}, drops {an['recall_drops']:.0%}). Drops to zero on low-volume series are inherently hard to separate from normal noise.", ""]
    if mon:
        L += ["## Monitoring", "", f"Retrain needed: **{mon['needs_retrain']}** - {', '.join(mon['reasons']) or 'no drift or degradation detected'}.", ""]
    p = PROJECT_ROOT / "docs" / "model_comparison_report.md"
    p.parent.mkdir(exist_ok=True)
    p.write_text("\n".join(L))
    return p
